#ifndef __GAME_API_H
#define __GAME_API_H

#include "./SYSTEM/sys/sys.h"

/* ==================== 输入命令(方向 + 动作) ==================== */
typedef enum
{
    CMD_NONE = 0,
    CMD_UP,          /* 上 */
    CMD_DOWN,        /* 下 */
    CMD_LEFT,        /* 左 */
    CMD_RIGHT,       /* 右 */
    CMD_ACTION,      /* 动作键(贪吃蛇/俄罗斯方块: 确认; 俄罗斯方块: 旋转) */
    CMD_RESTART,     /* 重开 */
    CMD_QUIT,        /* 退出游戏, 返回菜单 */
} game_cmd_t;

/* ==================== 统一游戏接口 ==================== */
typedef struct game
{
    const char *name;                   /* 游戏名(显示在菜单) */

    void (*init)(void);                 /* 初始化(进入游戏时调用一次) */
    void (*update)(void);               /* 逻辑更新(每帧调用) */
    void (*render)(void);               /* 渲染(每帧调用, 可空) */
    void (*on_input)(game_cmd_t cmd);   /* 输入回调(有输入事件时调用) */
    void (*exit)(void);                 /* 退出清理(返回菜单时调用) */
} game_t;

/* 游戏是否仍在运行(未退出到菜单) —— 由各游戏内部维护 */
/* 每个游戏模块需提供 `uint8_t xxx_is_running(void)` 返回 0 表示已退出 */

#endif /* __GAME_API_H */
